import ts from 'typescript';
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync('src/scenes/BattleScene.ts', 'utf8');
const ast = ts.createSourceFile('scene.ts', source, ts.ScriptTarget.Latest, true);
const cls = ast.statements.find(n => ts.isClassDeclaration(n));
const names = ['playDamageAnimations', 'playSmokeScreenArmEffect'];
const methods = cls.members.filter(n => names.includes(n.name?.getText(ast))).map(n => n.getText(ast)).join('\n');
const js = ts.transpile(`class Harness { ${methods} }; globalThis.Harness = Harness;`, {target: ts.ScriptTarget.ES2022});
const context = vm.createContext({NinjaSmokeVfx: class { constructor() { context.created++; } }, created: 0});
vm.runInContext(js, context);
for (const order of ['attack-first', 'smoke-first']) {
  const h = new context.Harness();
  h.battle = {enemies: [{id: 'ninja'}]};
  h.combatPositions = () => ({player: {}, enemy: {}});
  let impact, attackDone, smokeDone, evades = 0, done = 0;
  h.playPlayerAttackEffect = (_a,_b,_c,_d,hit,end) => {impact=hit; attackDone=end;};
  h.playSmokeSubstitutionEvadeEffect = (_e,_p,end) => {evades++; smokeDone=end;};
  h.playDamageAnimations([{type:'damage',attacker:'player',enemyId:'ninja',evaded:true}], () => done++);
  assert.equal(evades, 0, 'No dodge before impact');
  impact(); impact(); impact();
  assert.equal(evades, 1, 'A multi-hit attack plays dodge once');
  assert.equal(done, 0);
  (order === 'attack-first' ? attackDone : smokeDone)();
  assert.equal(done, 0, 'Queue waits for both attack and smoke');
  (order === 'attack-first' ? smokeDone : attackDone)();
  assert.equal(done, 1);
  attackDone(); smokeDone();
  assert.equal(done, 1, 'Queue completion is idempotent');
}
const h = new context.Harness();
const scheduled=[]; const poses=[]; let ready=0;
h.time={delayedCall:(ms,fn)=>scheduled.push({ms,fn})};
h.setEnemyPortraitPose=(_i,pose)=>poses.push(pose);
h.enemySeatCenter=()=>({x:0,y:0});
h.enemyHudLayout=()=>({portrait:{width:128,height:128}});
h.sound={play(){}};
h.playSmokeScreenArmEffect({sourceEnemyIndex:0},()=>ready++);
assert.equal(poses[0], 'cast'); assert.equal(context.created,0); assert.equal(ready,0);
assert.equal(scheduled[0].ms,320); scheduled.shift().fn();
assert.equal(context.created,1); assert.equal(ready,0);
assert.equal(scheduled[0].ms,650); scheduled.shift().fn();
assert.equal(poses.at(-1),'idle'); assert.equal(ready,1);
